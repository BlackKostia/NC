#!/usr/bin/env python3
"""Generate the built-in English interface table as C23 (docs/HYBRID_PORTABILITY_PLAN.md, step E2).

Inputs : include/types.inc  - the LangStrings slots (names + order = the ABI the assembly UI indexes with LangStrings.<name>)
         src/tui/i18n_en.lang - the English text, same `key = value` format as lang/*.lang (the pack loader's rules)
Output : <out>.c            - `const LangStrings lang_en_table` + `i18n_key_blob`, the slot names in slot order
                              ("code\\0name\\0...": the byte offset of key #n is n * 8, see src/tui/i18n_keys.c)

The build fails (exit 1) when a slot has no English text or a key is unknown or duplicated. File-scope output is
`const` pointers only, so `.data` stays empty."""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION_MARK = "\x00"                      # {version} inside a parsed value (NUL cannot occur in file text)
ESCAPES = {"n": "\n", "t": "\t", "\\": "\\", '"': '"'}
KEY_CHARS = re.compile(r"[A-Za-z0-9_.]+")


def slot_keys(types_text: str) -> list[str]:
    """Pack keys of every LangStrings slot in struct order; array fields are numbered from 1 (f_labels.1 ...)."""
    body = re.search(r"LangStrings\.code:.*?LangStrings\._size:", types_text, re.S)
    if not body:
        raise ValueError("include/types.inc has no LangStrings struct")
    keys: list[str] = []
    for line in body.group(0).splitlines():
        m = re.match(r"LangStrings\.(\w+):\s*\.space\s+(\d+)(?:\s*\*\s*(\d+))?", line)
        if not m or m.group(1) == "_size":
            continue
        n = (int(m.group(2)) * int(m.group(3)) if m.group(3) else int(m.group(2))) // 8
        keys += [m.group(1)] if n == 1 else [f"{m.group(1)}.{i + 1}" for i in range(n)]
    return keys


def parse_value(raw: str) -> str:
    """The loader's value rules (src/tui/i18n_pack.c ip_value): trailing blanks dropped, optional "quotes", escapes
    \\n \\t \\" \\\\ (any other backslash stays), {version} -> VERSION_MARK."""
    raw = raw.rstrip(" \t\r")
    quoted = raw.startswith('"')
    text = raw[1:] if quoted else raw
    out: list[str] = []
    i = 0
    while i < len(text):
        c = text[i]
        if c == '"' and quoted:
            break
        if c == "\\" and i + 1 < len(text) and text[i + 1] in ESCAPES:
            out.append(ESCAPES[text[i + 1]])
            i += 2
            continue
        if c == "{" and text.startswith("{version}", i):
            out.append(VERSION_MARK)
            i += 9
            continue
        out.append(c)
        i += 1
    return "".join(out)


def parse_lang(text: str) -> dict[str, str]:
    """key -> value; ValueError on duplicates (the loader would silently keep the last one)."""
    pairs: dict[str, str] = {}
    for n, line in enumerate(text.splitlines(), 1):
        stripped = line.lstrip(" \t")
        m = KEY_CHARS.match(stripped)
        if not m:
            continue
        rest = stripped[m.end():].lstrip(" \t")
        if not rest.startswith("="):
            continue
        if m.group(0) in pairs:
            raise ValueError(f"line {n}: duplicate key '{m.group(0)}'")
        pairs[m.group(0)] = parse_value(rest[1:].lstrip(" \t"))
    return pairs


def format_value(value: str) -> str:
    """Inverse of parse_value: quote only when blanks or a leading quote need protecting."""
    text = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    text = text.replace(VERSION_MARK, "{version}")
    return f'"{text}"' if text[:1] in (" ", "\t") or text[-1:] in (" ", "\t") else text


def c_literal(value: str) -> str:
    """A C string literal for `value`; VERSION_MARK becomes the DUOP_VERSION macro (adjacent-literal concatenation)."""
    pieces: list[str] = []
    for part in value.split(VERSION_MARK):
        body = []
        for ch in part:
            if ch == "\\" or ch == '"':
                body.append("\\" + ch)
            elif ch == "\n":
                body.append("\\n")
            elif ch == "\t":
                body.append("\\t")
            elif ord(ch) < 0x20 or ord(ch) == 0x7F:
                body.append(f"\\{ord(ch):03o}")
            else:
                body.append(ch)
        pieces.append('"' + "".join(body) + '"')
    return " DUOP_VERSION ".join(pieces)


def generate(types_text: str, lang_text: str) -> str:
    keys = slot_keys(types_text)
    pairs = parse_lang(lang_text)
    missing = [k for k in keys if k not in pairs]
    extra = [k for k in pairs if k not in keys]
    if missing or extra:
        raise ValueError(f"i18n_en.lang out of sync with LangStrings: missing {missing}, unknown {extra}")
    out = ["/* Generated by tools/gen_i18n.py from src/tui/i18n_en.lang and include/types.inc - do not edit. */",
           '#include "duop_tui.h"', '#include "version.h"', "",
           f'_Static_assert(LANG_SLOTS == {len(keys)}, "LangStrings slot count differs from include/types.inc");', "",
           "const LangStrings lang_en_table = {{"]
    out += [f"    {c_literal(pairs[k])},  /* {k} */" for k in keys]
    out += ["}};", "", "/* slot names in slot order, NUL-separated: key #n names the slot at byte offset n * 8 */", "const char i18n_key_blob[] ="]
    out += [f'    "{k}\\0"' for k in keys]
    out += [";", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--types", default=str(ROOT / "include/types.inc"))
    ap.add_argument("--lang", default=str(ROOT / "src/tui/i18n_en.lang"))
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    try:
        text = generate(Path(args.types).read_text(encoding="utf-8"), Path(args.lang).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"gen_i18n: {exc}", file=sys.stderr)
        return 1
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    tmp = Path(args.out + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
